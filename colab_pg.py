def plot_combined_feature_importances(if_selected_features, rf_selected_features, thresholds=[0.01, 0.02, 0.05]):
    for t in thresholds:
        if_df = if_ranked_features[if_ranked_features['if_importance'] >= t]
        rf_df = rf_ranked_features[rf_ranked_features['rf_importance'] >= t] # get dataframe instead of list


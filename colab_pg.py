def get_ranked_features(model_name, feature_names, feature_importances_):
    importance_col = f"{model_name}_importance"

    feature_imp_df = pd.DataFrame({
            'feature': feature_names,
        importance_col: feature_importances_
    })

    feature_imp_df = feature_imp_df.sort_values(by=importance_col, ascending=False).reset_index(drop=True)
    return feature_imp_df.set_index('feature')

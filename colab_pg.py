def clean_data(df):
    # tidy
    df.columns = df.columns.str.strip()
    df['Label'] = df['Label'].apply(lambda x: 0 if x == 'BENIGN' else 1).astype(int)
    df = df.drop(columns='Fwd Header Length.1') # duplicate column

    # clean
    df.drop_duplicates(inplace=True)

    # get features, prepare for interpolate()
    features = df.drop(columns= 'Label')
    labels = df['Label']

    # check missing values
    missing = features.isna().sum()
    print(missing.loc[missing > 0])

    # replace
    features.replace([np.inf, -np.inf], np.nan, inplace = True)

    categorical_columns = features.select_dtypes(include=['object']).columns
    print("Categorical columns:", categorical_columns)

    # handle
    features.interpolate(inplace=True)

    # Reattach labels for getting benign rows
    df = features.copy()
    df['Label'] = labels
    benign_data = df[df['Label'] == 0].drop(columns=['Label'])
    features = df.drop(columns= 'Label') # update features

    return features, labels, benign_data


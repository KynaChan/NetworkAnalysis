def compare_if_model_precision(
    model_name,
    true_labels,
    predictions_dict
):
    pred_labels_dict = list(predictions_dict.keys())
    accuracies = [
        precision_score(true_labels, predictions_dict[label]) for label in pred_labels_dict
    ]

    x = np.arange(len(pred_labels_dict))
    width = 0.6

    plt.figure(figsize=(10, 6))
    bars = plt.bar(x, accuracies)

    for bar in bars:
        height = bar.get_height()
        plt.text(bar.get_x() + bar.get_width() / 2, height + 0.01,
                 f'{height:.4f}', ha='center', va='bottom')

    plt.xticks(ticks=x, labels=pred_labels_dict, rotation=15)
    plt.ylim(0, 1.05)
    plt.ylabel("Precision")
    plt.title(f"Precision Comparison of {model_name} Models\n(with different feature sets)")
    plt.tight_layout()
    plt.show()
    plt.savefig(f"Precision Comparison of {model_name} Models (with different feature sets).png", bbox_inches='tight')


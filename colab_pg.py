def train_and_predict_if(benign, data): # benign  & all data
    if_model = IsolationForest(n_estimators=300)
    if_model.fit(benign)

    preds = pd.DataFrame(columns=['if_anomaly_score', 'if_raw_pred', 'if_pred'])
    preds['if_raw_pred'] = if_model.predict(data)
    preds['if_pred'] = preds['if_raw_pred'].replace({1: 0, -1: 1})  # returns 1 (normal), -1 (anomaly)
    preds['if_anomaly_score'] = -if_model.decision_function(data)
    return if_model, preds

